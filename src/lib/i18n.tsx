const DICTS: Record<Lang, Dict> = { de, en, ar, sq };

export type Translate = (key: string, vars?: Record<string, string | number>) => string;

interface Ctx {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: Translate;
  dir: "ltr" | "rtl";
}

const I18nContext = createContext<Ctx | null>(null);

const STORAGE_KEY = "mtk.lang";

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("de");
  setDateLocale(lang);

  useEffect(() => {
    const stored = window.localStorage.getItem(STORAGE_KEY) as Lang | null;
    if (stored && stored in DICTS) {
      setLangState(stored);
      return;
    }
    const nav = window.navigator.language.slice(0, 2) as Lang;
    if (nav in DICTS) setLangState(nav);
  }, []);

  useEffect(() => {
    setDateLocale(lang);
    const dir = lang === "ar" ? "rtl" : "ltr";
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
  }, [lang]);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    try {
      window.localStorage.setItem(STORAGE_KEY, next);
    } catch {
      /* ignore */
    }
  }, []);

  const t = useCallback<Translate>(
    (key, vars) => {
      const raw = DICTS[lang][key] ?? DICTS.en[key] ?? key;
      if (!vars) return raw;
      return raw.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
    },
    [lang],
  );

  const value = useMemo<Ctx>(
    () => ({ lang, setLang, t, dir: lang === "ar" ? "rtl" : "ltr" }),
    [lang, setLang, t],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

const fallbackT: Translate = (key, vars) => {
  const raw = DICTS.de[key] ?? DICTS.en[key] ?? key;
  return vars ? raw.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`)) : raw;
};

const FALLBACK: Ctx = {
  lang: "de",
  setLang: () => {},
  t: fallbackT,
  dir: "ltr",
};

export function useI18n() {
  return useContext(I18nContext) ?? FALLBACK;
}
